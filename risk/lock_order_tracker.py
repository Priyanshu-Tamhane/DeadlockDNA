"""
risk/lock_order_tracker.py — Lock-Order Acquisition Tracking (Feature D)

Tracks lock acquisition order per thread to construct a directed Lock Order Graph (LOG).
Detects inconsistent lock hierarchies (e.g. AB vs BA acquisitions) across threads and runs
before a deadlock actually stalls the system.
"""

from dataclasses import dataclass, field
import logging
from typing import Dict, List, Optional, Set, Tuple
import networkx as nx

from graph.models import Event, Operation, resource_node

logger = logging.getLogger(__name__)

DEFAULT_LOG_EDGE_TTL_NS = 60_000_000_000  # 60s TTL for lock order edges


@dataclass
class LockOrderEvidence:
    """Evidence metadata for a directed lock acquisition order edge (A -> B)."""
    src_resource: str
    dst_resource: str
    thread_id: int
    pid: int
    first_seen_ns: int
    last_seen_ns: int
    count: int = 1
    session_id: str = "default"

    def to_dict(self) -> Dict:
        return {
            "src_resource": self.src_resource,
            "dst_resource": self.dst_resource,
            "thread_id": self.thread_id,
            "pid": self.pid,
            "first_seen_ns": self.first_seen_ns,
            "last_seen_ns": self.last_seen_ns,
            "count": self.count,
            "session_id": self.session_id,
        }


class LockOrderTracker:
    """
    Tracks dynamic lock acquisition sequences per thread and maintains
    a directed Lock Order Graph (LOG) G = (V, E) where:
      - Vertices V are synchronization resources (e.g. M@pid:0xaddr or normalized).
      - Directed edge A -> B signifies that a thread acquired lock B while holding lock A.
    """

    def __init__(
        self,
        session_id: str = "default",
        ttl_ns: int = DEFAULT_LOG_EDGE_TTL_NS,
        prune_interval: int = 50,
    ) -> None:
        self.session_id = session_id
        self.ttl_ns = ttl_ns
        self.prune_interval = prune_interval
        self._event_count: int = 0
        # Directed graph where nodes are resource strings and edges contain evidence metadata
        self._log: nx.DiGraph = nx.DiGraph()
        # Per-thread held lock set with reentrant acquisition depth: tid -> {resource_id: depth}
        self._held_locks: Dict[int, Dict[str, int]] = {}
        # Historical evidence lookup: (src, dst) -> LockOrderEvidence
        self._evidence: Dict[Tuple[str, str], LockOrderEvidence] = {}

    @property
    def graph(self) -> nx.DiGraph:
        """Returns the directed Lock Order Graph."""
        return self._log

    def prune_stale_edges(self, current_ts_ns: int, force: bool = False) -> List[Tuple[str, str]]:
        """
        Prunes Lock Order Graph edges that have not been observed within TTL.
        Prevents unbounded graph growth and false positives in long-running sessions.
        """
        if self.ttl_ns <= 0 or not current_ts_ns:
            return []

        cutoff = current_ts_ns - self.ttl_ns
        stale_edges = [
            (u, v)
            for u, v, d in list(self._log.edges(data=True))
            if d.get("evidence") and d["evidence"].last_seen_ns < cutoff
        ]

        for u, v in stale_edges:
            self._log.remove_edge(u, v)
            self._evidence.pop((u, v), None)
            logger.debug("LOG -edge (TTL expired) %s -> %s", u, v)

        if stale_edges:
            isolated = [n for n in list(self._log.nodes()) if self._log.degree(n) == 0]
            self._log.remove_nodes_from(isolated)

        return stale_edges

    def process_event(self, event: Event) -> List[LockOrderEvidence]:
        """
        Updates lock tracking state based on synchronization events.
        Only LOCK_ACQUIRED and LOCK_RELEASED alter the held-lock state.
        LOCK_REQUEST does not infer acquisition.

        Returns:
            List of new or updated LockOrderEvidence records generated by this event.
        """
        self._event_count += 1
        if self.prune_interval > 0 and self._event_count % self.prune_interval == 0:
            self.prune_stale_edges(event.timestamp_ns)

        tid = event.tid
        res = event.scoped_resource
        ts = event.timestamp_ns
        pid = event.pid

        if event.operation == Operation.LOCK_ACQUIRED:
            return self._handle_acquire(tid, res, pid, ts)
        elif event.operation == Operation.LOCK_RELEASED:
            self._handle_release(tid, res)
            return []
        return []

    def _handle_acquire(self, tid: int, res: str, pid: int, ts: int) -> List[LockOrderEvidence]:
        held = self._held_locks.setdefault(tid, {})
        new_evidence: List[LockOrderEvidence] = []

        # If already held by this thread (reentrancy/recursive lock), increment depth and do not self-edge
        if res in held:
            held[res] += 1
            return []

        # For every lock currently held by this thread, record order: held_res -> res
        for held_res in list(held.keys()):
            if held_res == res:
                continue

            edge_key = (held_res, res)
            if edge_key in self._evidence:
                ev = self._evidence[edge_key]
                ev.count += 1
                ev.last_seen_ns = max(ev.last_seen_ns, ts)
                new_evidence.append(ev)
            else:
                ev = LockOrderEvidence(
                    src_resource=held_res,
                    dst_resource=res,
                    thread_id=tid,
                    pid=pid,
                    first_seen_ns=ts,
                    last_seen_ns=ts,
                    count=1,
                    session_id=self.session_id,
                )
                self._evidence[edge_key] = ev
                self._log.add_edge(held_res, res, evidence=ev)
                new_evidence.append(ev)
                logger.debug("LOG +edge %s -> %s (by T%d)", held_res, res, tid)

        # Mark resource as held by this thread
        held[res] = 1
        return new_evidence

    def _handle_release(self, tid: int, res: str) -> None:
        held = self._held_locks.get(tid)
        if not held or res not in held:
            return

        held[res] -= 1
        if held[res] <= 0:
            del held[res]

        if not held:
            del self._held_locks[tid]

    def clear_thread(self, tid: int) -> None:
        """Cleans up tracking state when a thread terminates."""
        if tid in self._held_locks:
            del self._held_locks[tid]

    def get_held_locks(self, tid: int) -> Set[str]:
        """Returns the set of resources currently held by a given thread."""
        return set(self._held_locks.get(tid, {}).keys())

    def get_all_held_locks(self) -> Dict[int, Set[str]]:
        """Returns a snapshot of held locks across all threads."""
        return {tid: set(locks.keys()) for tid, locks in self._held_locks.items()}

    def get_evidence(self, src: str, dst: str) -> Optional[LockOrderEvidence]:
        """Retrieves evidence recorded for an observed lock-order edge."""
        return self._evidence.get((src, dst))

    def reset_session(self, session_id: Optional[str] = None) -> None:
        """Resets held locks while retaining accumulated graph (or clears all if specified)."""
        self._held_locks.clear()
        if session_id:
            self.session_id = session_id

